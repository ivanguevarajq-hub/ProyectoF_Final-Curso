    private void iniciarReloj() {
        DateTimeFormatter formato = DateTimeFormatter.ofPattern("EEEE, d 'de' MMMM 'de' yyyy | hh:mm:ss a", new Locale("es", "ES"));
        Timer timer = new Timer(1000, e -> {
            LocalDateTime ahora = LocalDateTime.now();
            String fechaTexto = ahora.format(formato);
            fechaTexto = fechaTexto.substring(0, 1).toUpperCase() + fechaTexto.substring(1);

            lblFechaHora.setText(fechaTexto);
        });

        timer.start(); 
    }

