    private void btnEntregarMedicamentosActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEntregarMedicamentosActionPerformed
        try {
            int filaSeleccionada = tblDetalleReceta.getSelectedRow();

            if (filaSeleccionada == -1) {
                JOptionPane.showMessageDialog(this, "Por favor, seleccione un medicamento de la lista para entregar.", "Atención", JOptionPane.WARNING_MESSAGE);
                return;
            }

            int confirm = JOptionPane.showConfirmDialog(this, "¿Está seguro de registrar la entrega de este medicamento?", "Confirmar Entrega", JOptionPane.YES_NO_OPTION);
            if (confirm != JOptionPane.YES_OPTION) {
                return;
            }

            // Obtenemos ID de la Columna 0 y Cantidad Solicitada de la Columna 2
            int idMedicamento = Integer.parseInt(tblDetalleReceta.getValueAt(filaSeleccionada, 0).toString());
            int cantidadEntregar = Integer.parseInt(tblDetalleReceta.getValueAt(filaSeleccionada, 2).toString());

            // Procesar entrega y descuento de stock
            String mensajeResultado = logica.BLFarmacia.entregarMedicamento(idMedicamento, cantidadEntregar);

            JOptionPane.showMessageDialog(this, mensajeResultado, "Resultado de Entrega", JOptionPane.INFORMATION_MESSAGE);

            // Actualizamos los datos en pantalla
            btnBuscarDniActionPerformed(evt);

        } catch (excepciones.DatosInvalidosException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Atención", JOptionPane.WARNING_MESSAGE);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Ocurrió un error al entregar: " + ex.getMessage(), "Error System", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnEntregarMedicamentosActionPerformed

