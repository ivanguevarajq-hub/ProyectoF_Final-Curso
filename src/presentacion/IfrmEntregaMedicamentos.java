    private void btnBuscarDniActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarDniActionPerformed
        String dniOAtencion = txtDniPaciente.getText().trim();

        if (dniOAtencion.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese el DNI o N° de Atención del paciente.", "Atención", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            entidades.Receta receta = logica.BLFarmacia.buscarReceta(dniOAtencion);

            if (receta == null) {
                JOptionPane.showMessageDialog(this, "No se encontró ninguna receta con el DNI o N° de Atención: " + dniOAtencion, "Sin Resultados", JOptionPane.INFORMATION_MESSAGE);
                return;
            }

            entidades.Paciente p = receta.getAtencionMedica().getCita().getPaciente();
            lblPaciente.setText("PACIENTE: " + p.getNombres() + " " + p.getApellidos());
            lblAtencion.setText("ATENCION N°: " + receta.getAtencionMedica().getIdAtencion());

            // Cargar la tabla con los detalles
            DefaultTableModel model = (DefaultTableModel) tblDetalleReceta.getModel();
            model.setRowCount(0);

            for (entidades.DetalleReceta d : receta.getDetalles()) {
                entidades.Medicamento m = d.getMedicamento();
                model.addRow(new Object[]{
                    m.getIdMedicamento(),
                    m.getNombre(),
                    d.getCantidad(),
                    m.getStockActual(),
                    d.getIndicaciones()
                });
            }

        } catch (excepciones.DatosInvalidosException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Atención", JOptionPane.WARNING_MESSAGE);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Error al procesar la búsqueda: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnBuscarDniActionPerformed

