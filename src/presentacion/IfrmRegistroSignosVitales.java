    private void calcularIMC() {
        try {
            if (!txtPeso.getText().trim().isEmpty() && !txtTalla.getText().trim().isEmpty()) {
                double peso = Double.parseDouble(txtPeso.getText().trim());
                double tallaCm = Double.parseDouble(txtTalla.getText().trim());

                double tallaM = tallaCm / 100.0; // convertimos cm a metros
                double imc = peso / (tallaM * tallaM);

                txtIMC.setText(String.format("%.2f", imc)); // Muestra 2 decimales
            }
        } catch (NumberFormatException e) {
            txtIMC.setText("");
        }
    }

